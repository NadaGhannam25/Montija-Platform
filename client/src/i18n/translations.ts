export type Lang = "ar" | "en";

export const CATEGORY_MAP = [
  { ar: "الكل",           en: "All" },
  { ar: "حلويات",         en: "Sweets" },
  { ar: "موالح",          en: "Savories" },
  { ar: "هدايا",          en: "Gifts" },
  { ar: "عطور",           en: "Perfumes" },
  { ar: "مخبوزات",        en: "Bakery" },
  { ar: "منتجات يدوية",   en: "Handmade" },
] as const;

export type ArCategory = typeof CATEGORY_MAP[number]["ar"];
export type EnCategory = typeof CATEGORY_MAP[number]["en"];

export function categoryToAr(label: string): ArCategory {
  const found = CATEGORY_MAP.find(c => c.en === label || c.ar === label);
  return (found?.ar ?? "الكل") as ArCategory;
}

export function categoryLabel(cat: string, lang: Lang): string {
  const found = CATEGORY_MAP.find(c => c.ar === cat || c.en === cat);
  if (!found) return cat;
  return lang === "ar" ? found.ar : found.en;
}

